#!/usr/bin/env node
// Validates data/goc/*.json and writes data/goc.js. Usage: node tools/build-goc.mjs [--check-only] [files...]
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
let katex = null;
try { katex = require('katex'); require('katex/contrib/mhchem'); } catch { console.warn('! katex not found – skipping render validation'); }

export const TOPICS = ['Carbocation stability', 'Carbanion stability', 'Free radical stability', 'Alkene stability', 'Resonance & hyperconjugation',
  'Inductive effect', 'Aromaticity', 'Acidity', 'Basicity', 'Substituent effects (o/m/p)', 'Tautomerism & enol content',
  'Physical properties (bp, dipole, bond length)', 'Nucleophilicity', 'Leaving group ability', 'Electrophilicity & carbonyl reactivity',
  'SN1/SN2/E1/E2 reactivity', 'Electrophilic aromatic substitution', 'Rearrangements & migratory aptitude'];
const TYPES = ['order', 'compare', 'effect', 'mcq'];

const args = process.argv.slice(2);
const checkOnly = args.includes('--check-only');
let files = args.filter((a) => !a.startsWith('--'));
const dir = path.join(root, 'data/goc');
if (!files.length) files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => path.join(dir, f));

const errors = []; const all = []; const ids = new Map();
const inline = (text, where) => {
  if (typeof text !== 'string') { errors.push(`${where}: not a string`); return; }
  if ((text.match(/\$/g) || []).length % 2) errors.push(`${where}: unbalanced $`);
  if (!katex) return;
  const re = /\$([^$]+)\$/g; let m;
  while ((m = re.exec(text))) {
    try { katex.renderToString(m[1], { throwOnError: true, strict: false }); }
    catch (e) { errors.push(`${where}: KaTeX: ${e.message.split('\n')[0]} <<${m[1]}>>`); }
  }
};
for (const f of files) {
  let arr;
  try { arr = JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) { errors.push(`${path.basename(f)}: invalid JSON: ${e.message}`); continue; }
  for (const q of arr) {
    const w = `${path.basename(f)}:${q.id}`;
    if (!q.id || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(q.id)) errors.push(`${w}: bad id`);
    if (ids.has(q.id)) errors.push(`${w}: duplicate id`); else ids.set(q.id, 1);
    if (!TOPICS.includes(q.topic)) errors.push(`${w}: bad topic "${q.topic}"`);
    if (!TYPES.includes(q.type)) errors.push(`${w}: bad type "${q.type}"`);
    if (!['easy', 'medium', 'hard'].includes(q.difficulty)) errors.push(`${w}: bad difficulty`);
    if (!q.question) errors.push(`${w}: missing question`); else inline(q.question, w + ' question');
    if (!q.explanation) errors.push(`${w}: missing explanation`); else inline(q.explanation, w + ' explanation');
    if (q.trap) inline(q.trap, w + ' trap');
    if (q.type === 'order') {
      if (!q.criterion) errors.push(`${w}: order needs criterion`);
      if (!Array.isArray(q.items) || q.items.length < 3 || q.items.length > 6) errors.push(`${w}: order needs 3–6 items`);
      else { q.items.forEach((t, i) => inline(t, `${w} item${i}`)); if (new Set(q.items).size !== q.items.length) errors.push(`${w}: duplicate items`); }
    } else if (TYPES.includes(q.type)) {
      if (!Array.isArray(q.options) || q.options.length < 2 || q.options.length > 5) errors.push(`${w}: needs 2–5 options`);
      else { q.options.forEach((t, i) => inline(t, `${w} option${i}`)); if (!(Number.isInteger(q.answer) && q.answer >= 0 && q.answer < q.options.length)) errors.push(`${w}: bad answer index`); }
      if (q.type === 'effect' && q.options && q.options[0] !== 'Increases') errors.push(`${w}: effect options must be ["Increases","Decreases","Remains nearly the same"]`);
    }
    all.push(q);
  }
}
console.log(`${all.length} GOC questions in ${files.length} files`);
const byTopic = {}; all.forEach((q) => (byTopic[q.topic] = (byTopic[q.topic] || 0) + 1)); console.log(byTopic);
if (errors.length) { console.log(`\n${errors.length} problem(s):`); errors.forEach((e) => console.log(' - ' + e)); }
if (!checkOnly && !errors.length) {
  fs.writeFileSync(path.join(root, 'data/goc.js'), `// AUTO-GENERATED by tools/build-goc.mjs from data/goc/*.json - do not edit by hand\nwindow.GOC_QUESTIONS = ${JSON.stringify(all, null, 1)};\n`);
  console.log('wrote data/goc.js');
}
process.exit(errors.length ? 1 : 0);
