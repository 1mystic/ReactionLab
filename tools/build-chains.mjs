#!/usr/bin/env node
// Validates data/chains/*.json (multi-step reaction chains) and writes data/chains.js.
// Usage: node tools/build-chains.mjs [--check-only] [files...]
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
let katex = null;
try { katex = require('katex'); require('katex/contrib/mhchem'); } catch { console.warn('! katex not found - skipping render validation (npm i katex)'); }

const CATEGORIES = ['Hydrocarbons', 'Aromatic Compounds', 'Haloalkanes & Haloarenes', 'Alcohols, Phenols & Ethers', 'Aldehydes & Ketones',
  'Carboxylic Acids & Derivatives', 'Amines & Diazonium Salts', 'Biomolecules', 'Polymers', 'Qualitative Tests'];
const args = process.argv.slice(2);
const checkOnly = args.includes('--check-only');
let files = args.filter((a) => !a.startsWith('--'));
const dir = path.join(root, 'data/chains');
if (!files.length) files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => path.join(dir, f));

const errors = [], all = [], ids = new Map();
const norm = (s) => String(s || '').replace(/\s+/g, '').toLowerCase();
const tex = (src, where) => {
  if (!katex || !src) return;
  try { katex.renderToString(src, { throwOnError: true, strict: false }); }
  catch (e) { errors.push(`${where}: KaTeX error: ${e.message.split('\n')[0]}  <<${src}>>`); }
};
const inline = (t, where) => { if (typeof t !== 'string') return; const re = /\$([^$]+)\$/g; let m; while ((m = re.exec(t))) tex(m[1], where); };
const dash = (obj, where) => { if (/[–—]/.test(JSON.stringify(obj))) errors.push(`${where}: contains an en/em dash`); };

for (const f of files) {
  let arr;
  try { arr = JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) { errors.push(`${path.basename(f)}: invalid JSON: ${e.message}`); continue; }
  if (!Array.isArray(arr)) { errors.push(`${f}: not an array`); continue; }
  for (const c of arr) {
    const w = `${path.basename(f)}:${c.id || c.title}`;
    for (const k of ['id', 'title', 'start', 'startName', 'steps', 'chapters', 'difficulty']) if (!c[k]) errors.push(`${w}: missing ${k}`);
    if (c.id && !/^chain-[a-z0-9]+(-[a-z0-9]+)*$/.test(c.id)) errors.push(`${w}: id must be kebab-case starting with chain-`);
    if (ids.has(c.id)) errors.push(`${w}: duplicate id (also in ${ids.get(c.id)})`); else ids.set(c.id, path.basename(f));
    if (!Array.isArray(c.chapters) || !c.chapters.length || c.chapters.length > 3 || c.chapters.some((x) => !CATEGORIES.includes(x))) errors.push(`${w}: chapters must be 1-3 of CATEGORIES`);
    if (!['easy', 'medium', 'hard'].includes(c.difficulty)) errors.push(`${w}: bad difficulty`);
    if (c.exam && (!Array.isArray(c.exam) || c.exam.some((x) => !['JEE Main', 'JEE Advanced'].includes(x)))) errors.push(`${w}: bad exam`);
    if (!Array.isArray(c.steps) || c.steps.length < 2 || c.steps.length > 5) { errors.push(`${w}: needs 2-5 steps`); continue; }
    tex(`\\ce{${c.start}}`, `${w} start`);
    let prev = c.start;
    c.steps.forEach((s, i) => {
      const sw = `${w} step ${i + 1}`;
      for (const k of ['reagent', 'product', 'productName', 'reaction', 'explanation']) if (!s[k]) errors.push(`${sw}: missing ${k}`);
      if (!Array.isArray(s.distractors) || s.distractors.length !== 3) errors.push(`${sw}: needs exactly 3 distractors`);
      const opts = [s.product, ...(s.distractors || [])].map(norm);
      if (new Set(opts).size !== opts.length) errors.push(`${sw}: options are not all different`);
      if (norm(s.product) === norm(prev)) errors.push(`${sw}: product equals the substrate`);
      const leak = [s.productName, s.reaction].filter(Boolean).some((t) => t.length > 4 && `${s.reagent} ${s.conditions || ''}`.toLowerCase().includes(t.toLowerCase()));
      if (leak) errors.push(`${sw}: reagent/conditions reveal the product or reaction name`);
      tex(`\\ce{${prev} ->[${s.reagent || ''}][${s.conditions || ''}] ${s.product}}`, `${sw} equation`);
      (s.distractors || []).forEach((d, j) => tex(`\\ce{${d}}`, `${sw} distractor ${j + 1}`));
      inline(s.explanation, `${sw} explanation`);
      prev = s.product;
    });
    dash(c, w);
    all.push(c);
  }
}
console.log(`${all.length} chains (${all.reduce((n, c) => n + (c.steps || []).length, 0)} steps) in ${files.length} files`);
if (errors.length) { console.log(`\n${errors.length} problem(s):`); errors.forEach((e) => console.log(' - ' + e)); }
if (!checkOnly) {
  if (errors.length) { console.log('\nNot writing chains.js because of errors.'); process.exit(1); }
  fs.writeFileSync(path.join(root, 'data/chains.js'), `// AUTO-GENERATED by tools/build-chains.mjs from data/chains/*.json - do not edit by hand\nwindow.CHAINS = ${JSON.stringify(all, null, 1)};\n`);
  console.log('wrote data/chains.js');
}
process.exit(errors.length ? 1 : 0);
