#!/usr/bin/env node
// Generates assets/js/firebase-config.js (git-ignored) from the local, git-ignored `.env` file.
// Runs automatically before `firebase deploy --only hosting` (see firebase.json "predeploy"),
// so the Firebase web config is never committed to the repository.
//
// .env holds the object from Firebase console > Project settings > Your apps > SDK setup, e.g.
//   apiKey: "...", authDomain: "...", projectId: "...", storageBucket: "...",
//   messagingSenderId: "...", appId: "..."
// (KEY=value lines are accepted too.)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(root, '.env');
const outPath = path.join(root, 'assets/js/firebase-config.js');
const REQUIRED = ['apiKey', 'authDomain', 'projectId', 'appId'];
const KEYS = ['apiKey', 'authDomain', 'projectId', 'storageBucket', 'messagingSenderId', 'appId'];

if (!fs.existsSync(envPath)) {
  if (fs.existsSync(outPath)) { console.log('firebase-config: no .env, keeping existing assets/js/firebase-config.js'); process.exit(0); }
  console.error('Missing .env. Copy the Firebase web config from the console into .env (see assets/js/firebase-config.example.js).');
  process.exit(1);
}
const text = fs.readFileSync(envPath, 'utf8');
const cfg = {};
for (const k of KEYS) {
  const m = text.match(new RegExp(`(?:^|[\\s,{])${k}\\s*[:=]\\s*["']?([^"',\\n\\r]+)["']?`));
  if (m) cfg[k] = m[1].trim();
}
const missing = REQUIRED.filter((k) => !cfg[k]);
if (missing.length) { console.error(`.env is missing: ${missing.join(', ')}`); process.exit(1); }
fs.writeFileSync(outPath, `// GENERATED by tools/write-firebase-config.mjs from .env. Git-ignored: do not commit.\nexport const firebaseConfig = ${JSON.stringify(cfg, null, 2)};\n`);
console.log(`firebase-config: wrote assets/js/firebase-config.js (${Object.keys(cfg).length} fields)`);
