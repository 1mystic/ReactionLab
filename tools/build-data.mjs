#!/usr/bin/env node
// Validates data/parts/*.json and merges them into data/reactions.js
// Usage: node tools/build-data.mjs [--check-only] [file.json ...]
// KaTeX validation runs if `katex` can be resolved (set NODE_PATH or npm i katex).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
let katex = null;
try {
  katex = require('katex');
  require('katex/contrib/mhchem');
} catch { console.warn('! katex not found – skipping render validation'); }

const CATEGORIES = ['Hydrocarbons', 'Aromatic Compounds', 'Haloalkanes & Haloarenes', 'Alcohols, Phenols & Ethers',
  'Aldehydes & Ketones', 'Carboxylic Acids & Derivatives', 'Amines & Diazonium Salts', 'Biomolecules & Polymers', 'Qualitative Tests'];
const KINDS = ['Named reaction', 'Rearrangement', 'Oxidation', 'Reduction', 'Distinguishing test', 'Industrial process', 'General reaction'];

const args = process.argv.slice(2);
const checkOnly = args.includes('--check-only');
let files = args.filter(a => !a.startsWith('--'));
const partsDir = path.join(root, 'data/parts');
if (!files.length) files = fs.readdirSync(partsDir).filter(f => f.endsWith('.json')).sort().map(f => path.join(partsDir, f));

const errors = [];
const all = [];
const ids = new Map();

function tex(src, where) {
  if (!katex || !src) return;
  try { katex.renderToString(src, { throwOnError: true, strict: false }); }
  catch (e) { errors.push(`${where}: KaTeX error: ${e.message.split('\n')[0]}  <<${src}>>`); }
}
function inlineTex(text, where) {
  if (typeof text !== 'string') return;
  const re = /\$([^$]+)\$/g; let m;
  while ((m = re.exec(text))) tex(m[1], where);
}

for (const f of files) {
  let arr;
  try { arr = JSON.parse(fs.readFileSync(f, 'utf8')); }
  catch (e) { errors.push(`${path.basename(f)}: invalid JSON: ${e.message}`); continue; }
  if (!Array.isArray(arr)) { errors.push(`${f}: not an array`); continue; }
  for (const r of arr) {
    const w = `${path.basename(f)}:${r.id || r.name}`;
    for (const k of ['id', 'name', 'category', 'kind', 'reactants', 'products', 'summary'])
      if (!r[k]) errors.push(`${w}: missing ${k}`);
    if (r.id && !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(r.id)) errors.push(`${w}: id not kebab-case`);
    if (ids.has(r.id)) errors.push(`${w}: duplicate id (also in ${ids.get(r.id)})`); else ids.set(r.id, path.basename(f));
    if (!CATEGORIES.includes(r.category)) errors.push(`${w}: bad category "${r.category}"`);
    if (!KINDS.includes(r.kind)) errors.push(`${w}: bad kind "${r.kind}"`);
    if (r.difficulty && !['easy', 'medium', 'hard'].includes(r.difficulty)) errors.push(`${w}: bad difficulty`);
    for (const k of ['aliases', 'exam', 'reagentKeywords', 'keyPoints', 'applications', 'examples', 'tags'])
      if (r[k] !== undefined && !Array.isArray(r[k])) errors.push(`${w}: ${k} must be array`);
    const eq = `${r.reactants} ->[${r.reagents || ''}][${r.conditions || ''}] ${r.products}`;
    tex(`\\ce{${eq}}`, `${w} equation`);
    (r.examples || []).forEach((ex, i) => { tex(`\\ce{${ex.eq}}`, `${w} example[${i}]`); inlineTex(ex.note, w); });
    for (const k of ['summary', 'mechanism', 'whenUsed', 'jeeTips', 'productName', 'catalyst']) inlineTex(r[k], `${w} ${k}`);
    for (const k of ['keyPoints', 'applications']) (r[k] || []).forEach(t => inlineTex(t, `${w} ${k}`));
    all.push(r);
  }
}

console.log(`${all.length} reactions in ${files.length} files`);
if (errors.length) { console.log(`\n${errors.length} problem(s):`); errors.forEach(e => console.log(' - ' + e)); }
if (!checkOnly) {
  if (errors.length) { console.log('\nNot writing reactions.js because of errors.'); process.exit(1); }
  const out = `// AUTO-GENERATED by tools/build-data.mjs from data/parts/*.json — do not edit by hand\nwindow.REACTIONS = ${JSON.stringify(all, null, 1)};\n`;
  fs.writeFileSync(path.join(root, 'data/reactions.js'), out);
  console.log('wrote data/reactions.js');
}
process.exit(errors.length ? 1 : 0);
